#!/bin/sh
# Regenerates docs/plans/INDEX.md from the plan files.
# Run from anywhere in the repo: scripts/gen-plan-index.sh
set -eu

cd "$(git rev-parse --show-toplevel)"
dir=docs/plans
out=$dir/INDEX.md

{
  echo "# Plan index"
  echo
  echo "Auto-generated by \`scripts/gen-plan-index.sh\` — do not edit by hand."
  echo
  echo "| План | Статус | Описание |"
  echo "|---|---|---|"
  for f in "$dir"/*.md; do
    base=$(basename "$f")
    case "$base" in README.md|TEMPLATE.md|INDEX.md) continue ;; esac
    head_line=$(grep -m1 '^# ' "$f" || true)
    if [ -n "$head_line" ]; then name=${head_line#\# }; else name=${base%.md}; fi
    # Нумерованные планы: id — часть заголовка до « — »; старые планы с
    # описательными именами идентифицируются по имени файла.
    case "$base" in
      [0-9]*-*.md) plan_id=${name%% — *} ;;
      *) plan_id=${base%.md} ;;
    esac
    status=$(grep -m1 '^\*\*Статус:\*\*' "$f" | sed 's/\*\*Статус:\*\* *//')
    [ -n "$status" ] || status=—
    # Описание: первая строка после «## …Цель» (шаблонные планы); если такой
    # секции нет (старые планы) — первая содержательная строка после H1
    # (без статуса, комментариев-подсказок и заголовков).
    goal=$(awk '
      in_goal && $0 == "" { next }
      in_goal { sub(/\.$/, ""); gsub(/\|/, "\\|"); print; exit }
      /^## .*Цель/ { in_goal=1; next }
      !title_seen { if ($0 ~ /^# /) title_seen=1; next }
      in_comment { if ($0 ~ /-->/) in_comment=0; next }
      /^<!--/ { if ($0 !~ /-->/) in_comment=1; next }
      in_status { if ($0 == "") in_status=0; next }
      $0 ~ /^\*\*Статус:\*\*/ || $0 ~ /^[Сс]татус:/ { in_status=1; next }
      generic_done || $0 == "" { next }
      $0 ~ /^## / || $0 ~ /^\[[^]]*\]\([^)]*\)$/ { next }
      { generic=$0; generic_done=1 }
      END {
        if (generic_done) {
          sub(/\.$/, "", generic); gsub(/\|/, "\\|", generic); print generic
        }
      }
    ' "$f")
    echo "| [\`$plan_id\`]($base) | $status | ${goal:-} |"
  done
} > "$out"

echo "wrote $out"
